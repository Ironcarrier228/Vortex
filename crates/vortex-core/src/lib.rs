//! # vortex-core
//!
//! Вся «умная» логика приложения, которая **не** зависит ни от Windows API, ни от Tauri:
//!
//! * [`audio`] — оконный FFT-анализ PCM → 64 лог-полосы в дБ (для сцены аудиовизуализатора);
//! * [`netdiff`] — дифференцирование снимков таблицы соединений (что появилось/исчезло);
//! * [`disk`] — сборка дерева каталогов из потока записей сканера + категоризация расширений.
//!
//! Разделение намеренное: это ядро компилируется и тестируется на любой ОС
//! (`cargo test -p vortex-core`), а платформенные провайдеры живут в `src-tauri`.

pub mod audio;
pub mod disk;
pub mod netdiff;

/// Приводит значение в дБ к [0,1] по «приятной» для визуализации шкале.
/// Та же формула продублирована во фронтенде (`src/core/audio/bus.ts`) — держать в синхроне.
#[inline]
pub fn db_to_unit(db: f32) -> f32 {
    ((db + 72.0) / 72.0).clamp(0.0, 1.0)
}
