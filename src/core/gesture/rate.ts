/**
 * Частота распознавания рук в зависимости от частоты отрисовки.
 *
 * Модель MediaPipe и сцена делят один GPU, поэтому 30 Гц распознавания на слабой машине
 * роняют картинку (наблюдали 10 FPS при 213 мс на кадр). Схема простая: пока рендер
 * свободен — 30 Гц, при просадке — 20, при совсем плохой картинке — 12 Гц. Сглаживание
 * курса и гистерезис щипка работают на кадрах рендера, поэтому редкие кадры распознавания
 * ощущаются как чуть более «тяжёлая» рука, но не как рывки изображения.
 */

/** Порог «рендер свободен». */
export const RATE_FULL = 45;
/** Порог «рендер просел, но терпимо». */
export const RATE_MEDIUM = 30;

/** Целевая частота распознавания для текущего FPS отрисовки. */
export function economyRate(renderFps: number): number {
  if (!Number.isFinite(renderFps) || renderFps <= 0) return 30;
  if (renderFps >= RATE_FULL) return 30;
  if (renderFps >= RATE_MEDIUM) return 20;
  return 12;
}
